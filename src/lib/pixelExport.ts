          const env = 1 - d / reach;
          ev = env * env;
          const phase = field.seed[i] * 6.283;
          const turb = calm ? 0 : ev * driftK;
          tx = (vx / d) * ev * pushK
             + turb * Math.sin(time * 0.9 + (field.gx[i] / field.cols) * 28 + phase)
             + turb * 0.5 * Math.sin(time * 1.9 + phase * 1.7);
